Types of SQL Commands:


1. DDL (Data Definition Language)
These commands are used to define the structure of the database and its objects. 
Examples: CREATE, ALTER, DROP, TRUNCATE and RENAME.
-- ###################################################################



2. DML (Data Manipulation Language)
These commands are used to manipulate the data within the database. 
Examples: INSERT, UPDATE, and DELETE.

* DQL (Data Query Language)
These commands are used to query the data in the database. 
Examples: SELECT.
-- ###################################################################



3. DCL (Data Control Language)
These commands are used to control access to the data in the database. 
Examples: GRANT and REVOKE.

* TCL (Transaction Control Language)
These commands are used to control transactions in the database. 
Examples: COMMIT, ROLLBACK and START TRANSACTION.
-- ###################################################################